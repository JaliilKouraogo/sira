function daysFrom(base: string, delta: number): string {
  const d = new Date(`${base}T12:00:00Z`);
  d.setUTCDate(d.getUTCDate() + delta);
  return d.toISOString().slice(0, 10);
}

export const ago = (n: number) => daysFrom(TODAY, -n);
export const inDays = (n: number) => daysFrom(TODAY, n);

